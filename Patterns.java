public class Patterns {
    public static void main(String[] args) {
        FirstPattern();
        SecondPattern();
        ThirdPattern();
    }

    public static void FirstPattern() {
        System.out.println("*");
        System.out.println("**");
        System.out.println("***");
        System.out.println("****");
        System.out.println("*****\n\n");
    }

    public static void SecondPattern() {
        System.out.println("*****");
        System.out.println("****");
        System.out.println("***");
        System.out.println("**");
        System.out.println("*\n\n");
    }

    public static void ThirdPattern() {
        System.out.println("    *");
        System.out.println("   **");
        System.out.println("  ***");
        System.out.println(" ****");
        System.out.println("*****");
    }
}
